// Lightweight enhancement: reveal sections as they enter the viewport.
const items = document.querySelectorAll('.card,.steps div,.problem-grid div');
const observer = new IntersectionObserver(entries => {
  entries.forEach(e => {
    if (e.isIntersecting) {
      e.target.style.opacity = '1';
      e.target.style.transform = 'translateY(0)';
      observer.unobserve(e.target);
    }
  });
}, {threshold:.12});
items.forEach(el => {
  el.style.opacity = '0';
  el.style.transform = 'translateY(18px)';
  el.style.transition = 'opacity .6s ease, transform .6s ease';
  observer.observe(el);
});
